def _check_mode_22(mode):
    """Require the scalar dominant spherical-harmonic mode."""
    if mode != 22:
        raise ValueError("IMRPhenomT shared fits only support mode=22")


def _s_tot_r(eta, s1, s2, delta=None):
    """Return ``(m1**2*s1 + m2**2*s2)/(m1**2 + m2**2)`` without masses.

    The equivalent expression avoids two redundant square roots and is
    compatible with scalar, PyTorch, and JAX array inputs.
    """
    if delta is None:
        delta = (1 - 4 * eta) ** 0.5
    return 0.5 * (s1 + s2) + delta * (s1 - s2) / (2 * (1 - 2 * eta))


