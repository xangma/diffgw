def IMRPhenomX_FinalMass2017(eta, s1, s2, delta=None):
    """
    Final mass fit for aligned spin
    """
    if delta is None:
        delta = (1 - 4 * eta) ** 0.5
    eta2 = eta * eta
    eta3 = eta2 * eta
    eta4 = eta3 * eta
    S = _s_tot_r(eta, s1, s2, delta)
    S2 = S * S
    S3 = S2 * S
    dchi = s1 - s2
    dchi2 = dchi * dchi
    eqSpin = (0.057190958417936644 * eta + 0.5609904135313374 * eta2 - 0.84667563764404 * eta3 + 3.145145224278187 * eta4) * (1 + (-0.13084389181783257 - 1.1387311580238488 * eta + 5.49074464410971 * eta2) * S + (-0.17762802148331427 + 2.176667900182948 * eta2) * S2 + (-0.6320191645391563 + 4.952698546796005 * eta - 10.023747993978121 * eta2) * S3) / (1 + (-0.9919475346968611 + 0.367620218664352 * eta + 4.274567337924067 * eta2) * S)
