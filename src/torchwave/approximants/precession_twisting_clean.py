"""Independent frequency-domain twisting algebra from Pratten et al. Eq. (45)."""
from __future__ import annotations

import math
import torch


def wigner_d(l: int, m: int, mp: int, beta):
    """Real Wigner small-d element using the finite factorial sum (Eq. 45)."""
    if not (-l <= m <= l and -l <= mp <= l):
        raise ValueError("magnetic indices must lie in [-l,l]")
    # Keep a floating Tensor's dtype/device and autograd history.  Python and
    # integer inputs retain the historical double-precision scalar behavior.
    if isinstance(beta, torch.Tensor):
        b = beta if beta.is_floating_point() else beta.to(dtype=torch.float64)
    else:
        b = torch.as_tensor(beta, dtype=torch.float64)
    c, s = torch.cos(b/2), torch.sin(b/2)
    pref = math.sqrt(math.factorial(l+m)*math.factorial(l-m)*
                      math.factorial(l+mp)*math.factorial(l-mp))
    total = torch.zeros_like(b)
    for k in range(0, 2*l+1):
        a = l + mp - k
        q = k
        r = m - mp + k
        z = l - m - k
        if min(a, q, r, z) < 0:
            continue
        total = total + ((-1.) ** (k + m - mp)) * pref / (
            math.factorial(a)*math.factorial(q)*math.factorial(r)*math.factorial(z)
        ) * c**(2*l + mp - m - 2*k) * s**(m - mp + 2*k)
    return total


def twist_mode(l, m, alpha, gamma, beta, coprecessing_modes):
    """Rotate coprecessing ``h_lm`` modes into a J frame.

    The dictionary maps ``m'`` to same-grid complex tensors.  Since the clean
    MSA API returns ``gamma=-epsilon``, Eq. (45)'s factor is
    ``exp(-i*m'*gamma) exp(-i*m*alpha) d^l_{m m'}(beta)``.
    """
    a = torch.as_tensor(alpha, dtype=torch.float64)
    g = torch.as_tensor(gamma, dtype=torch.float64, device=a.device)
    b = torch.as_tensor(beta, dtype=torch.float64, device=a.device)
    out = torch.zeros_like(next(iter(coprecessing_modes.values())), dtype=torch.complex128)
    for mp, h in coprecessing_modes.items():
        d = wigner_d(l, m, int(mp), b).to(device=h.device)
        out = out + torch.exp(-1j*int(mp)*g) * d * h
    return torch.exp(-1j*int(m)*a) * out


def project_twisted_positive_modes(coprecessing_modes, alpha, gamma, beta,
                                   theta_jn, zeta):
    """Project positive-frequency coprecessing modes after Eq. (45).

    ``coprecessing_modes[(ell, mprime)]`` is the supplied positive-frequency
    value of ``h_{ell,-mprime}``, with ``mprime > 0``.  The companion term is
    generated by the standard reality relation in the Eq. (18)--(19)
    polarization sum.  The spin-weighted harmonic is evaluated at azimuth
    zero, and the final complex strain is inverse-rotated by ``zeta``.
    This is an equation-level helper; it does not call a waveform model.
    """
    if not coprecessing_modes:
        raise ValueError("at least one positive-m mode is required")
    alpha = torch.as_tensor(alpha, dtype=torch.float64)
    gamma = torch.as_tensor(gamma, dtype=torch.float64, device=alpha.device)
    beta = torch.as_tensor(beta, dtype=torch.float64, device=alpha.device)
    theta = torch.as_tensor(theta_jn, dtype=torch.float64, device=alpha.device)
    zeta = torch.as_tensor(zeta, dtype=torch.float64, device=alpha.device)
    hp = torch.zeros_like(next(iter(coprecessing_modes.values())), dtype=torch.complex128)
    hc = torch.zeros_like(hp)
    for (ell, mp), hneg in coprecessing_modes.items():
        if mp <= 0:
            raise ValueError("mode keys must have positive mprime")
        hneg = torch.as_tensor(hneg, dtype=torch.complex128)
        for m in range(-ell, ell + 1):
            # _{-2}Y_lm(theta,0) = sqrt((2l+1)/(4pi)) d^l_{m,2}(theta)
            # in the active-rotation convention used by Eq. (45).
            y = math.sqrt((2 * ell + 1) / (4 * math.pi)) * wigner_d(ell, m, 2, theta)
            aminus = torch.exp(-1j * m * alpha) * wigner_d(ell, m, -mp, beta) * y
            aplus = torch.exp(-1j * m * alpha) * wigner_d(ell, m, mp, beta) * y
            pref = torch.exp(1j * mp * gamma) * hneg
            parity_aplus = ((-1) ** ell) * torch.conj(aplus)
            hp = hp + 0.5 * pref * (aminus + parity_aplus)
            hc = hc + 0.5j * pref * (aminus - parity_aplus)
    # Eq. (146): zeta is a real polarization-basis rotation, applied to the
    # complex Fourier coefficients of the two real polarizations.
    c2, s2 = torch.cos(2 * zeta), torch.sin(2 * zeta)
    return c2 * hp + s2 * hc, c2 * hc - s2 * hp
