def _clenshaw(x: torch.Tensor, coefficients: tuple) -> torch.Tensor:
    """Evaluate a Chebyshev series using only Torch arithmetic and scalar constants."""
    b1 = torch.zeros_like(x)
    b2 = torch.zeros_like(x)
    for coefficient in reversed(coefficients[1:]):
        b0 = 2 * x * b1 - b2 + coefficient
        b2, b1 = b1, b0
    return x * b1 - b2 + coefficients[0]


def evaluate_kerr_qnm_220(a_final: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
    """Return Re(M_f*omega) and -Im(M_f*omega), preserving shape/device/dtype.

    Negative spin represents the positive-spin m=-2 branch by Kerr symmetry.
    The approximation is smooth through zero. Inputs outside the validated
    domain [-0.9999, 0.9999] are clamped to its endpoints.
    """
    if not a_final.is_floating_point():
        raise TypeError("Kerr spin must be a floating-point tensor")
    spin = a_final.clamp(min=-0.9999, max=0.9999)
    t = torch.sqrt(1 - spin)
    x = 2 * (t - 0.01) / (1.414178206592083 - 0.01) - 1
    return (_clenshaw(x, _FREQUENCY_COEFFICIENTS),
            t * _clenshaw(x, _DAMPING_COEFFICIENTS))
