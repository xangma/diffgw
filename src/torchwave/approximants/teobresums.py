class TEOBResumSRadiationReaction:
    """Clean nonspinning vacuum mode-sum torque, with zero radial force.

    Requires a supported Hamiltonian and the complete current orbital state.
    """

    def __init__(
        self,
        nu: torch.Tensor,
        chi1: torch.Tensor,
        chi2: torch.Tensor,
        *,
        include_horizon_absorption: bool = True,
    ):
        if bool(torch.any(chi1 != 0)) or bool(torch.any(chi2 != 0)):
            raise ValueError("TEOB radiation supports only nonspinning vacuum parameters.")
        self.nu, self.chi1, self.chi2 = nu, chi1, chi2
        if not isinstance(include_horizon_absorption, bool):
            raise TypeError("include_horizon_absorption must be a bool")
        self.include_horizon_absorption = include_horizon_absorption
        self._clean_radiation = TEOBRadiationClean(8, residual_phase="zero-unpublished")

    @staticmethod
    def _is_zero_tensor(value: object) -> bool:
        """Return whether an intrinsic tensor is identically zero."""
        return isinstance(value, torch.Tensor) and bool(torch.all(value == 0))

    @classmethod
    def _is_nonspinning_vacuum(cls, hamiltonian: object) -> bool:
        """Select only the zero-spin, zero-tide clean component route."""
        return (
            hasattr(hamiltonian, "clean_radiation_inputs")
            and cls._is_zero_tensor(getattr(hamiltonian, "chi1", None))
            and cls._is_zero_tensor(getattr(hamiltonian, "chi2", None))
            and cls._is_zero_tensor(getattr(hamiltonian, "lambda1", None))
            and cls._is_zero_tensor(getattr(hamiltonian, "lambda2", None))
            and cls._is_zero_tensor(getattr(hamiltonian, "kappa3_1", None))
            and cls._is_zero_tensor(getattr(hamiltonian, "kappa3_2", None))
        )

    def radiation_reaction_forces(self, omega, pr_star, pphi, *, r=None,
                                  hamiltonian=None,
                                  include_horizon_absorption: bool | None = None):
        if (
            r is not None
            and hamiltonian is not None
            and self._is_nonspinning_vacuum(hamiltonian)
        ):
            if include_horizon_absorption is None:
                include_horizon_absorption = self.include_horizon_absorption
            if not isinstance(include_horizon_absorption, bool):
                raise TypeError("include_horizon_absorption must be a bool or None")

            # The clean mode sum needs the current effective and real energies,
            # plus the circular real energy and independent A'(r).  Hcirc is
            # evaluated at p_r*=0 while retaining the *current* p_phi; this
            # is the chain-rule state in 1406.6913 Eqs. (69)--(76).
            h_eff, h_real, h_circ, a_prime = hamiltonian.clean_radiation_inputs(
                r, pr_star, pphi,
            )
            flux = self._clean_radiation.flux(
                r,
                omega,
                torch.zeros_like(omega),
                pr_star,
                pphi,
                h_eff,
                h_real,
                h_circ,
                a_prime,
                hamiltonian.m1,
                hamiltonian.m2,
                include_horizon=include_horizon_absorption,
            )
            nu = hamiltonian.nu
            if omega.dim() > nu.dim():
                nu = nu.unsqueeze(-1)
            # The clean component returns physical angular flux.  Eq. (36)
            # divides by eta once to obtain the reduced azimuthal force.
            torque = -flux / nu
            # TEOBResumS sets the radial dissipative force to zero.
            return torch.zeros_like(torque), torque
        raise ValueError("TEOB radiation requires r and a nonspinning vacuum Hamiltonian; prototype fallbacks are unavailable.")


class TEOBResumSHamiltonian(_HamiltonianBase):
    """Nonspinning vacuum Hamiltonian with the published TEOB orbital potential."""

    def __init__(self, nu, chi1=0.0, chi2=0.0, lambda1=0.0, lambda2=0.0,
                 lambda1_oct=None, lambda2_oct=None, cq1=None, cq2=None,
                 delta=None, r_lr=3.0):
        nu = torch.as_tensor(nu)
        values = [torch.as_tensor(value, dtype=nu.dtype, device=nu.device)
                  for value in (chi1, chi2, lambda1, lambda2)]
        for value in (*values, lambda1_oct, lambda2_oct):
            if value is not None and bool(torch.any(torch.as_tensor(value) != 0)):
                raise ValueError("TEOB Hamiltonian supports only nonspinning vacuum parameters; spin and tidal prototypes are unavailable.")
        nu, chi1, chi2, lambda1, lambda2 = torch.broadcast_tensors(nu, *values)
        if r_lr != 3.0 or cq1 is not None or cq2 is not None:
            raise ValueError("TEOB Hamiltonian supports only nonspinning vacuum parameters; tidal and quadrupole options are unavailable.")
        self.nu, self.chi1, self.chi2 = nu, chi1, chi2
        self.lambda1, self.lambda2 = lambda1, lambda2
        self.delta = torch.sqrt(torch.clamp(1.0 - 4.0 * nu, min=0.0)) if delta is None else delta
        self.x1 = self.m1 = 0.5 * (1.0 + self.delta)
        self.x2 = self.m2 = 0.5 * (1.0 - self.delta)
        self.kappa3_1 = self.kappa3_2 = torch.zeros_like(nu)


    def point_mass_metric_potentials(self, r: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        """Return TEOBResumS point-mass ``(A, B, xi)``.

        The orbital ``A`` is the calibrated 5PN-log ``P^1_5`` potential from
        Nagar et al. (2015).  ``D=A B`` remains the published inverse-Taylor
        3PN expression, and the quartic radial Hamiltonian term is supplied
        separately by the inherited ``z3`` factor.
        """
        u = 1.0 / r
        a_potential = _teobresums_orbital_potential(u, self.nu)
        nu = self.nu
        if r.dim() > nu.dim():
            nu = nu.unsqueeze(-1)
        d_potential = 1.0 / (
            1.0 + 6.0 * nu * u.square()
            + 2.0 * nu * (26.0 - 3.0 * nu) * u.pow(3)
        )
        b_potential = d_potential / a_potential
        xi = a_potential / torch.sqrt(d_potential)
        return a_potential, b_potential, xi

    def metric_potentials(self, r):
        """Return published vacuum point-mass (A, B, xi)."""
        return self.point_mass_metric_potentials(r)

    def centrifugal_radius_squared(self, r):
        """The nonspinning centrifugal radius equals the orbital radius."""
        return r ** 2


    def effective_hamiltonian(self, r, pr_star, pphi):
        """Nonspinning tortoise mass shell, Damour--Nagar Eq. (7)."""
        nu = self.nu
        if r.dim() > nu.dim():
            nu = nu.unsqueeze(-1)
        a_pot = self.metric_potentials(r)[0]
        z3 = 2.0 * nu * (4.0 - 3.0 * nu)
        return torch.sqrt(pr_star ** 2 + a_pot * (
            1.0 + (pphi ** 2 + z3 * pr_star ** 4) / r ** 2))

    def real_hamiltonian_from_eff(self, h_eff: torch.Tensor) -> torch.Tensor:
        """Compute the real Hamiltonian H_real / M = sqrt(1 + 2*nu*(H_eff - 1))."""
        nu = self.nu
        if h_eff.dim() > nu.dim():
            nu = nu.unsqueeze(-1)
        radicand = 1.0 + 2.0 * nu * (h_eff - 1.0)
        return torch.sqrt(torch.clamp(radicand, min=1e-6))

    def real_hamiltonian(
        self,
        r: torch.Tensor,
        pr_star: torch.Tensor,
        pphi: torch.Tensor,
    ) -> torch.Tensor:
        """Compute real Hamiltonian H_real / M."""
        h_eff = self.effective_hamiltonian(r, pr_star, pphi)
        return self.real_hamiltonian_from_eff(h_eff)

    def clean_radiation_inputs(
        self,
        r: torch.Tensor,
        pr_star: torch.Tensor,
        pphi: torch.Tensor,
    ) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
        """Build the explicit state consumed by the clean TEOB radiation sum.

        The returned tuple is ``(H_eff, H, Hcirc, A_prime)``.  ``H_eff`` and
        ``H`` are evaluated at the current ``(r, p_r*, p_phi)``.  ``Hcirc``
        is the *real total* Hamiltonian at ``(r, 0, p_phi)``: only the radial
        momentum is replaced by zero, while the evolving angular momentum is
        retained.  ``A_prime`` is a coordinate partial derivative at fixed
        momenta, obtained by differentiating the metric potential with an
        independent radius node.  These are the chain-rule inputs to
        1406.6913 Eqs. (69)--(76), and avoid substituting an effective energy
        or a circular angular momentum for the quantities in the radiation
        equations.

        Local autograd graphs are retained when any state or Hamiltonian
        parameter requires gradients and are detached under inference/no-grad
        contexts, matching :meth:`equations_of_motion_conservative`.
        """
        tensors = (r, pr_star, pphi, *vars(self).values())
        track_grad = torch.is_grad_enabled() and any(
            value.requires_grad for value in tensors if isinstance(value, torch.Tensor)
        )
        with torch.inference_mode(False), torch.enable_grad():
            # Expand shared scalar coordinates before taking a partial.  A
            # scalar state with batched Hamiltonian parameters must receive
            # one independent A'(r) per parameter row; differentiating a
            # single shared node would otherwise sum those rows.
            r, pr_star, pphi = torch.broadcast_tensors(r, pr_star, pphi)
            with torch.no_grad():
                batch_shape = self.effective_hamiltonian(r, pr_star, pphi).shape
            r_eval = r.expand(batch_shape)
            pr_eval = pr_star.expand(batch_shape)
            pphi_eval = pphi.expand(batch_shape)

            h_eff = self.effective_hamiltonian(r_eval, pr_eval, pphi_eval)
            h_real = self.real_hamiltonian_from_eff(h_eff)
            h_eff_circ = self.effective_hamiltonian(
                r_eval, torch.zeros_like(pr_eval), pphi_eval,
            )
            h_circ = self.real_hamiltonian_from_eff(h_eff_circ)

            # A'(r) is a coordinate partial.  Materializing a fresh radius
            # node prevents a shared state graph from turning this into a
            # total derivative through any caller-side expression.
            r_node = r_eval.clone().requires_grad_(True)
            a_node = self.metric_potentials(r_node)[0]
            a_prime = torch.autograd.grad(
                a_node.sum(), r_node, create_graph=track_grad,
            )[0]

        result = (h_eff, h_real, h_circ, a_prime)
        if track_grad:
            return result
        return tuple(value.detach() for value in result)

    # Descriptive alias for callers that use the paper's ``A'`` notation.
    radiation_inputs = clean_radiation_inputs

    def _metric_potential_prime(self, r: torch.Tensor) -> torch.Tensor:
        """Return the independent coordinate derivative ``dA/dr``."""
        tensors = (r, *vars(self).values())
        track_grad = torch.is_grad_enabled() and any(
            value.requires_grad for value in tensors if isinstance(value, torch.Tensor)
        )
        with torch.inference_mode(False), torch.enable_grad():
            # ``metric_potentials`` already broadcasts its parameter axes; use
            # the first potential's shape directly and avoid a shared scalar
            # derivative when parameters are batched.
            a_shape = self.metric_potentials(r)[0].shape
            r_node = r.expand(a_shape).clone().requires_grad_(True)
            a_node = self.metric_potentials(r_node)[0]
            result = torch.autograd.grad(
                a_node.sum(), r_node, create_graph=track_grad,
            )[0]
        return result if track_grad else result.detach()

    def metric_potential_derivative(self, r: torch.Tensor) -> torch.Tensor:
        """Return the coordinate partial ``A'(r)`` used by ``r_Omega``."""
        return self._metric_potential_prime(r)

    metric_potential_prime = metric_potential_derivative

    def equations_of_motion_conservative(
        self,
        r: torch.Tensor,
        pr_star: torch.Tensor,
        pphi: torch.Tensor,
    ) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        """Return conservative tortoise derivatives, including tidal gradients.

        Use the common EOB partial-derivative calculation, with independent
        coordinate nodes and inference support. Track tidal and quadrupole
        parameters as well as masses, spins and state coordinates.
        """
        track_grad = torch.is_grad_enabled() and any(
            value.requires_grad for value in (r, pr_star, pphi, *vars(self).values())
            if isinstance(value, torch.Tensor)
        )
        result = self._conservative_partials(r, pr_star, pphi)
        return result if track_grad else tuple(value.detach() for value in result)

    def equations_of_motion(
        self,
        r: torch.Tensor,
        pr_star: torch.Tensor,
        pphi: torch.Tensor,
        rr: TEOBResumSRadiationReaction,
    ) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
        """Compute full conservative and dissipative time derivatives.

        Returns:
            (dr_dt, omega, dpr_star_dt, dpphi_dt)
        """
        dr_dt, omega, dpr_star_cons = self.equations_of_motion_conservative(
            r, pr_star, pphi)

        # Dissipative radiation reaction forces
        f_r_star, f_phi = rr.radiation_reaction_forces(
            omega, pr_star, pphi, r=r, hamiltonian=self)

        dpr_star_dt = dpr_star_cons + f_r_star
        dpphi_dt = f_phi

        return dr_dt, omega, dpr_star_dt, dpphi_dt


def _teobresums_centrifugal_radius(
    r: torch.Tensor,
    nu: torch.Tensor,
    chi1: torch.Tensor,
    chi2: torch.Tensor,
    cq1: Optional[torch.Tensor] = None,
    cq2: Optional[torch.Tensor] = None,
    delta: Optional[torch.Tensor] = None,
) -> torch.Tensor:
    """Return the aligned-spin centrifugal radius r_c = sqrt(r_c^2)."""
    r_arr = as_tensor(r, dtype=torch.float64)
    nu_arr = as_tensor(nu, dtype=torch.float64)
    s1_arr = as_tensor(chi1, dtype=torch.float64)
    s2_arr = as_tensor(chi2, dtype=torch.float64)
    if delta is None:
        delta = torch.sqrt(torch.clamp(1.0 - 4.0 * nu_arr, min=0.0))
    else:
        delta = as_tensor(delta, dtype=torch.float64)
    x1 = 0.5 * (1.0 + delta)
    x2 = 0.5 * (1.0 - delta)
    a1 = s1_arr * x1
    a2 = s2_arr * x2
    cq1_val = 1.0 if cq1 is None else as_tensor(cq1, dtype=torch.float64)
    cq2_val = 1.0 if cq2 is None else as_tensor(cq2, dtype=torch.float64)
    if r_arr.dim() > a1.dim():
        a1 = a1.unsqueeze(-1)
        a2 = a2.unsqueeze(-1)
        cq1_val = torch.as_tensor(cq1_val, dtype=r_arr.dtype, device=r_arr.device).unsqueeze(-1)
        cq2_val = torch.as_tensor(cq2_val, dtype=r_arr.dtype, device=r_arr.device).unsqueeze(-1)
    a_q_sq = cq1_val * (a1 ** 2) + 2.0 * a1 * a2 + cq2_val * (a2 ** 2)
    rc2 = (r_arr ** 2) + a_q_sq * (1.0 + 2.0 / r_arr)
    return torch.sqrt(rc2)
