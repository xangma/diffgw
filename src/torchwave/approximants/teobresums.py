def _piecewise_linear_fourier(signal: torch.Tensor, event_time: torch.Tensor,
                              dt_sec: torch.Tensor, frequencies: torch.Tensor) -> torch.Tensor:
    """Integrate a sampled signal, linearly interpolated, through ``event_time``.

    ``signal`` has shape ``(T,)`` or ``(T, B)`` and event_time is in seconds.
    The interval formula is evaluated in normalized coordinates, with series
    for the two entire functions at zero frequency.  This is differentiable
    in the signal, event time, and sample spacing.
    """
    batched = signal.dim() == 2
    if not batched:
        signal = signal.unsqueeze(-1)
        event_time = event_time.reshape(1)
        dt_sec = dt_sec.reshape(1)
    b = signal.shape[1]
    f = frequencies.reshape(-1)
    n_intervals = signal.shape[0] - 1
    idx = torch.arange(n_intervals, device=signal.device, dtype=signal.dtype)
    start = idx[:, None] * dt_sec[None, :]
    end = torch.minimum((idx[:, None] + 1.0) * dt_sec[None, :], event_time[None, :])
    length = torch.clamp(end - start, min=0.0)
    interval = torch.floor(event_time / dt_sec).to(torch.long)
    valid = idx.to(torch.long)[:, None] < interval[None, :]
    final = idx.to(torch.long)[:, None] == interval[None, :]
    y0 = signal[:-1]
    y1 = signal[1:]
    alpha = torch.clamp((event_time[None, :] - start) / dt_sec[None, :], 0.0, 1.0)
    y_end = torch.where(final, y0 + alpha * (y1 - y0), y1)
    y_end = torch.where(valid | final, y_end, y0)
    # Broadcast (interval, batch, frequency) while retaining chunking at caller.
    q = torch.complex(torch.zeros((n_intervals, b, f.numel()), dtype=signal.dtype, device=signal.device),
                      -2.0 * PI * length[..., None] * f.view(1, 1, -1))
    small = q.abs() < 1e-3
    q2 = q * q
    j0_series = 1.0 + q / 2.0 + q2 / 6.0 + q2 * q / 24.0 + q2 * q2 / 120.0
    j1_series = 0.5 + q / 3.0 + q2 / 8.0 + q2 * q / 30.0 + q2 * q2 / 144.0
    expq = torch.exp(q)
    # Safe denominators avoid NaNs in the unused branch of torch.where,
    # which otherwise can contaminate gradients at exactly f=0.
    q_safe = torch.where(small, torch.ones_like(q), q)
    q2_safe = q_safe * q_safe
    j0 = torch.where(small, j0_series, torch.expm1(q) / q_safe)
    j1 = torch.where(small, j1_series, ((q - 1.0) * expq + 1.0) / q2_safe)
    phase = torch.exp(torch.complex(torch.zeros_like(start[..., None]),
                                    -2.0 * PI * start[..., None] * f.view(1, 1, -1)))
    result = (length[..., None] * phase *
              (y0[..., None] * j0 + (y_end - y0)[..., None] * j1)).sum(dim=0)
    return result[0] if not batched else result


def _teobresums_orbital_potential(u: torch.Tensor, nu: torch.Tensor) -> torch.Tensor:
    """Return the published TEOBResumS ``P^1_5[A_orb^PN]`` potential.

    Nagar et al., arXiv:1506.08457v2, Eqs. (1)--(3), specify the 5PN-log
    series and the calibrated ``a6c`` polynomial.  The exact 4PN coefficient
    is from Bini--Damour, arXiv:1305.4884, Eqs. (2), (6), and the logarithmic
    5PN coefficient is from Damour--Jaranowski--Schaefer,
    arXiv:1502.07245, Eq. (A13).  The Padé equations are solved over the
    coefficient ring generated by ``log(u)``; this is the direct formal
    meaning of applying ``P^1_5`` to the printed log series.
    """
    if u.dim() > nu.dim():
        nu = nu.unsqueeze(-1)
    u, nu = torch.broadcast_tensors(u, nu)
    one = torch.ones_like(u)
    pi = torch.as_tensor(PI, dtype=u.dtype, device=u.device)
    gamma_e = torch.as_tensor(0.577215664901532860606512090082402431,
                              dtype=u.dtype, device=u.device)
    ln2 = torch.as_tensor(math.log(2.0), dtype=u.dtype, device=u.device)

    a4 = one * ((94.0 / 3.0) - (41.0 / 32.0) * pi.square())
    a50 = (-4237.0 / 60.0 + (2275.0 / 512.0) * pi.square()
           + (256.0 / 5.0) * ln2 + (128.0 / 5.0) * gamma_e)
    a51 = (41.0 / 32.0) * pi.square() - 221.0 / 6.0
    a5c = a50 + a51 * nu
    a5log = one * (64.0 / 5.0)
    a6c = 3097.3 * nu.square() - 1330.6 * nu + 81.38
    a6log = -7004.0 / 105.0 - (144.0 / 5.0) * nu
    log_u = torch.log(u)

    # A_PN = sum(c[n] u**n), with log(u) retained in c[5] and c[6].
    c = [
        one,
        -2.0 * one,
        torch.zeros_like(u),
        2.0 * nu,
        nu * a4,
        nu * (a5c + a5log * log_u),
        nu * (a6c + a6log * log_u),
    ]
    # For (1,5), matching coefficients at orders 2..6 gives a 5x5
    # linear system for denominator coefficients d1..d5.  c[n<0] is zero.
    rows = []
    rhs = []
    for n in range(2, 7):
        rows.append(torch.stack([
            c[n - j] if n - j >= 0 else torch.zeros_like(u)
            for j in range(1, 6)
        ], dim=-1))
        rhs.append(-c[n])
    matrix = torch.stack(rows, dim=-2)
    zero_mass = nu == 0
    # The exact test-mass series is only linear, so its formal (1,5) Padé
    # system is singular.  Give those rows a harmless identity pivot and use
    # the analytically specified Schwarzschild branch below.
    identity = torch.eye(5, dtype=u.dtype, device=u.device)
    matrix = matrix + identity * zero_mass.unsqueeze(-1).unsqueeze(-1)
    denominator_coeffs = torch.linalg.solve(
        matrix, torch.stack(rhs, dim=-1).unsqueeze(-1)
    ).squeeze(-1)
    powers = torch.stack([u ** j for j in range(1, 6)], dim=-1)
    denominator = one + (denominator_coeffs * powers).sum(dim=-1)
    numerator = one + (c[1] + denominator_coeffs[..., 0]) * u
    pade = numerator / denominator
    return torch.where(zero_mass, 1.0 - 2.0 * u, pade)
