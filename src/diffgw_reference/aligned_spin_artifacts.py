"""Regenerate aligned-spin TaylorF2 equations and high-precision fixtures.

Run from the repository root: python -m diffgw_reference.aligned_spin_artifacts
[--check]. Snapshots preserve reviewed math; they are not a second oracle.
"""

import argparse
import json
from pathlib import Path

import sympy as sp

from . import taylorf2_aligned_spin as ref
from .artifacts import _digits


CASES = (
    ("equal_mass", "25", "0.0003", "0", "0.6", "0.6", "0.7"),
    ("zero_spin", "20", "0.0000133", "0.04", "0", "0", "1.2"),
    ("opposed_spins", "80", "0.00027", "0.8", "-0.8", "0.7", "0"),
    ("near_reference", "40.0000000000000000000001", "0.0000133",
     "0.04", "0.3", "-0.2", "0.7"),
)


def fixtures():
    """Freeze all physical spin terms, with convergence checked at 100/160 dps."""
    result = {
        "spec_version": ref.SPEC_VERSION,
        "base_spec_version": ref.base.SPEC_VERSION,
        "sources": ref.SOURCES,
        "terms": list(ref.SPIN_TERMS),
        "working_precision_dps": [100, 160],
        "stored_significant_digits": 65,
        "inputs": (
            "Exact decimal strings; M_sec and D_sec in seconds; f and f_ref in Hz; "
            "delta=(m1-m2)/(m1+m2); chi1/chi2 dimensionless aligned spins; angles in radians."
        ),
        "cases": [],
    }
    expressions_by_mode = {}
    for use_ref in (False, True):
        expressions = dict(ref.waveform_expr(reference_frequency=use_ref))
        for key, variable in (("df", ref.F), ("dchi1", ref.CHI1), ("dchi2", ref.CHI2)):
            expressions[f"dphase_{key}"] = ref.derivative_expr(expressions["phase"], variable)
        expressions["dh_plus_dchi1"] = ref.derivative_expr(expressions["h_plus"], ref.CHI1)
        expressions["dh_cross_dchi2"] = ref.derivative_expr(expressions["h_cross"], ref.CHI2)
        expressions_by_mode[use_ref] = expressions
    for name, frequency, mass, delta, chi1, chi2, inclination in CASES:
        values = dict(f=frequency, M_sec=mass, delta=delta, chi1=chi1, chi2=chi2,
                      D_sec="10000000000000000", iota=inclination,
                      tc="0.01", phic="0.2", f_ref="40")
        for use_ref, expressions in expressions_by_mode.items():
            numbers = {}
            for key, expr in expressions.items():
                low = ref.evaluate(expr, values, dps=100)
                high = ref.evaluate(expr, values, dps=160)
                if abs(low - high) > max(abs(high), high.context.mpf("1e-100")) * high.context.mpf("1e-65"):
                    raise ArithmeticError(f"precision did not converge: {name}/{use_ref}/{key}")
                numbers[key] = _digits(high)
            result["cases"].append({"name": name, "reference_frequency": use_ref,
                                    "parameters": values, "expected": numbers})
    return result


def coefficient_table():
    """Render individual spin corrections from the canonical scalar expressions."""
    lines = ["<!-- Generated by python -m diffgw_reference.aligned_spin_artifacts; do not edit by hand. -->",
             "", "| Spin term | Exact correction |", "| --- | --- |"]
    for name, expression in ref.spin_corrections().items():
        lines.append(f"| `{name}` | ${sp.latex(expression, mul_symbol='dot')}$ |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd(), help="DiffGW repository root")
    parser.add_argument("--check", action="store_true", help="Fail if maintained artifacts differ")
    args = parser.parse_args()
    files = {
        "docs/math/taylorf2-aligned-spin-coefficients.md": coefficient_table(),
        "tests/data/taylorf2_aligned_spin_reference_v1.json": json.dumps(fixtures(), indent=2) + "\n",
    }
    for relative, content in files.items():
        path = args.root / relative
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"Reference artifact needs regeneration: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        print(f"{'Checked' if args.check else 'Wrote'} {relative}")


if __name__ == "__main__":
    main()
