"""Regenerate the maintained TaylorF2 equation table and numerical fixtures.

Run from the repository root: python -m diffgw_reference.artifacts [--check].
The fixture is a reviewable snapshot, not an additional independent oracle.
"""

import argparse
import json
from pathlib import Path

import mpmath
import sympy as sp

from . import taylorf2 as ref


CASES = (
    ("equal_mass", "25", "0.0003", "0.25", "0.7"),
    ("small_mass", "20", "0.0000133", "0.249", "1.2"),
    ("asymmetric", "80", "0.00027", "0.08", "0"),
    ("near_reference", "40.0000000000000000000001", "0.0000133", "0.249", "0.7"),
)


def _digits(value):
    if hasattr(value, "imag") and value.imag:
        return {"real": mpmath.nstr(value.real, 65), "imag": mpmath.nstr(value.imag, 65)}
    return mpmath.nstr(value.real, 65)


def fixtures():
    result = {
        "spec_version": ref.SPEC_VERSION,
        "sources": ref.SOURCES,
        "working_precision_dps": [100, 160],
        "stored_significant_digits": 65,
        "inputs": "Exact decimal strings; M_sec and D_sec in seconds; f and f_ref in Hz; angles in radians.",
        "cases": [],
    }
    for name, frequency, mass, eta, inclination in CASES:
        values = dict(f=frequency, M_sec=mass, eta=eta, D_sec="10000000000000000",
                      iota=inclination, tc="0.01", phic="0.2", f_ref="40")
        for use_ref in (False, True):
            expressions = dict(ref.waveform_expr(reference_frequency=use_ref))
            expressions["dphase_df"] = ref.derivative_expr(expressions["phase"], ref.F)
            expressions["dphase_deta"] = ref.derivative_expr(expressions["phase"], ref.ETA)
            expressions["dh_plus_dM_sec"] = ref.derivative_expr(expressions["h_plus"], ref.M_SEC)
            numbers = {}
            for key, expr in expressions.items():
                # Near-reference mass-ratio derivatives cancel over 20 digits.
                low = ref.evaluate(expr, values, dps=100)
                high = ref.evaluate(expr, values, dps=160)
                # Require agreement much tighter than FP64 frontend thresholds.
                if abs(low - high) > max(abs(high), high.context.mpf("1e-100")) * high.context.mpf("1e-65"):
                    raise ArithmeticError(f"precision did not converge: {name}/{use_ref}/{key}")
                numbers[key] = _digits(high)
            result["cases"].append({"name": name, "reference_frequency": use_ref,
                                    "parameters": values, "expected": numbers})
    return result


def coefficient_table():
    lines = ["<!-- Generated by python -m diffgw_reference.artifacts; do not edit by hand. -->", "",
             "| Component ID | Exact coefficient |", "| --- | --- |"]
    for name, expression in ref.coefficients().items():
        lines.append(f"| `{ref.COMPONENT_IDS[name]}` | ${sp.latex(expression)}$ |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd(), help="DiffGW repository root")
    parser.add_argument("--check", action="store_true", help="Fail if maintained artifacts differ")
    args = parser.parse_args()
    files = {
        "docs/math/taylorf2-coefficients.md": coefficient_table(),
        "tests/data/taylorf2_reference_v1.json": json.dumps(fixtures(), indent=2) + "\n",
    }
    for relative, content in files.items():
        path = args.root / relative
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"Reference artifact needs regeneration: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        print(f"{'Checked' if args.check else 'Wrote'} {relative}")


if __name__ == "__main__":
    main()
