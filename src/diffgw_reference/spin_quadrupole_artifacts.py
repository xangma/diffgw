"""Regenerate versioned spin-quadrupole equations and high-precision fixtures."""

import argparse
import json
from pathlib import Path

import sympy as sp

from . import taylorf2_spin_quadrupole as ref
from .artifacts import _digits


CASES = (
    ("equal_mass", "80", "0.0000138", "0", "0.2", "-0.1", "4", "6", "400", "400"),
    ("unequal_mass", "120", "0.0000133", "0.12", "0.3", "0.07", "3", "8", "200", "800"),
    ("black_hole_neutron_star", "80", "0.0000414", "0.666666666666666666666666666666666666666666666666666666666666667",
     "0.5", "0.02", "1", "5", "0", "500"),
    ("kerr_limit", "80", "0.0000133", "0.12", "0.3", "0.07", "1", "1", "200", "800"),
)


def fixtures():
    mode_expressions = {}
    for use_ref in (False, True):
        wave = ref.waveform_expr(reference_frequency=use_ref)
        expressions_by_mode = dict(ref.quadrupole_corrections())
        expressions_by_mode.update({key: wave[key] for key in ("phase", "h_plus", "h_cross")})
        expressions_by_mode["dphase_dCQ1"] = ref.derivative_expr(wave["phase"], ref.CQ1)
        expressions_by_mode["dphase_dCQ2"] = ref.derivative_expr(wave["phase"], ref.CQ2)
        expressions_by_mode["dphase_df"] = ref.derivative_expr(wave["phase"], ref.F)
        mode_expressions[use_ref] = expressions_by_mode
    result = {
        "spec_version": ref.SPEC_VERSION,
        "inherited_spec_versions": ref.INHERITED_SPEC_VERSIONS,
        "sources": {key: ref.SOURCES[key] for key in ("nagar2018", "dietrich2019")},
        "quadrupole_terms": list(ref.QUAD_TERMS),
        "working_precision_dps": [100, 160],
        "stored_significant_digits": 65,
        "inputs": "Exact decimal strings; M_sec/D_sec in seconds, f/f_ref in Hz; C_Qi=1 is Kerr; octupoles fixed at Kerr; no EOS relation.",
        "cases": [],
    }
    for name, frequency, mass, delta, chi1, chi2, cq1, cq2, lambda1, lambda2 in CASES:
        values = dict(f=frequency, M_sec=mass, delta=delta, chi1=chi1, chi2=chi2,
                      C_Q1=cq1, C_Q2=cq2, lambda1=lambda1, lambda2=lambda2,
                      D_sec="10000000000000000", iota="0.7", tc="0.01", phic="0.2", f_ref="40")
        for use_ref, expressions in mode_expressions.items():
            numbers = {}
            for key, expression in expressions.items():
                low = ref.evaluate(expression, values, dps=100)
                high = ref.evaluate(expression, values, dps=160)
                if abs(low-high) > max(abs(high), high.context.mpf("1e-100"))*high.context.mpf("1e-65"):
                    raise ArithmeticError(f"precision did not converge: {name}/{use_ref}/{key}")
                numbers[key] = _digits(high)
            result["cases"].append({"name": name, "reference_frequency": use_ref,
                                    "parameters": values, "expected": numbers})
    return result


def coefficient_table():
    lines = ["<!-- Generated by python -m diffgw_reference.spin_quadrupole_artifacts; do not edit by hand. -->",
             "", "| Phase term | Exact expression inside 3/(128 eta v^5) | Evidence |",
             "| --- | --- | --- |"]
    for name, expression in ref.quadrupole_corrections().items():
        source, *equations = ref.COMPONENT_SOURCES[ref.COMPONENT_IDS[name]]
        lines.append(f"| `{name}` | ${sp.latex(expression, mul_symbol='dot')}$ | "
                     f"[{source}]({ref.SOURCES[source]['url']}), Eq. {', '.join(equations)} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = {
        "docs/math/taylorf2-spin-quadrupole-coefficients.md": coefficient_table(),
        "tests/data/taylorf2_spin_quadrupole_reference_v1.json": json.dumps(fixtures(), indent=2)+"\n",
    }
    for relative, content in files.items():
        path = args.root / relative
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"Reference artifact needs regeneration: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        print(f"{'Checked' if args.check else 'Wrote'} {relative}")


if __name__ == "__main__":
    main()
