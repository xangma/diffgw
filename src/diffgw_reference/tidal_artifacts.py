"""Regenerate tidal TaylorF2 equations and high-precision fixtures.

Run from the repository root: python -m diffgw_reference.tidal_artifacts
[--check]. Snapshots preserve reviewed math; they are not a second oracle.
"""

import argparse
import json
from pathlib import Path

import sympy as sp

from . import taylorf2_tidal as ref
from .artifacts import _digits


CASES = (
    ("equal_mass", "400", "0.0000138", "0", "0", "0", "500", "500", "0.7"),
    ("unequal_tides", "700", "0.0000133", "0.12", "0.04", "-0.02", "250", "850", "1.2"),
    ("black_hole_neutron_star", "150", "0.0000345", "0.6", "0.5", "0", "0", "600", "0"),
    ("zero_tides", "80", "0.00027", "0.8", "-0.8", "0.7", "0", "0", "0.7"),
    ("near_reference", "40.0000000000000000000001", "0.0000133", "0.04",
     "0.03", "-0.02", "300", "700", "0.7"),
)


def fixtures():
    """Freeze the composed phase and tides at independently checked precision."""
    result = {
        "spec_version": ref.SPEC_VERSION,
        "base_spec_version": ref.base.SPEC_VERSION,
        "aligned_spin_spec_version": ref.aligned.SPEC_VERSION,
        "sources": ref.SOURCES,
        "spin_terms": list(ref.aligned.SPIN_TERMS),
        "tidal_terms": list(ref.TIDAL_TERMS),
        "working_precision_dps": [100, 160],
        "stored_significant_digits": 65,
        "inputs": (
            "Exact decimal strings; M_sec and D_sec in seconds; f and f_ref in Hz; "
            "delta=(m1-m2)/(m1+m2); chi1/chi2 aligned spins and lambda1/lambda2 "
            "quadrupolar tidal deformabilities are dimensionless; angles in radians."
        ),
        "cases": [],
    }
    expressions_by_mode = {}
    for use_ref in (False, True):
        expressions = dict(ref.waveform_expr(reference_frequency=use_ref))
        expressions.update(ref.tidal_parameters())
        expressions.update(ref.tidal_corrections())
        for key, variable in (("df", ref.F), ("dlambda1", ref.LAMBDA1),
                              ("dlambda2", ref.LAMBDA2)):
            expressions[f"dphase_{key}"] = ref.derivative_expr(expressions["phase"], variable)
        expressions["dh_plus_dlambda1"] = ref.derivative_expr(expressions["h_plus"], ref.LAMBDA1)
        expressions["dh_cross_dlambda2"] = ref.derivative_expr(expressions["h_cross"], ref.LAMBDA2)
        expressions_by_mode[use_ref] = expressions
    for name, frequency, mass, delta, chi1, chi2, lambda1, lambda2, inclination in CASES:
        values = dict(f=frequency, M_sec=mass, delta=delta, chi1=chi1, chi2=chi2,
                      lambda1=lambda1, lambda2=lambda2, D_sec="10000000000000000",
                      iota=inclination, tc="0.01", phic="0.2", f_ref="40")
        for use_ref, expressions in expressions_by_mode.items():
            numbers = {}
            for key, expr in expressions.items():
                low = ref.evaluate(expr, values, dps=100)
                high = ref.evaluate(expr, values, dps=160)
                if abs(low - high) > max(abs(high), high.context.mpf("1e-100")) * high.context.mpf("1e-65"):
                    raise ArithmeticError(f"precision did not converge: {name}/{use_ref}/{key}")
                numbers[key] = _digits(high)
            result["cases"].append({"name": name, "reference_frequency": use_ref,
                                    "parameters": values, "expected": numbers})
    return result


def coefficient_table():
    """Render both published bases from the exact scalar expressions."""
    lines = ["<!-- Generated by python -m diffgw_reference.tidal_artifacts; do not edit by hand. -->",
             "", "| Tidal parameter | Exact expression |", "| --- | --- |"]
    for name, expression in ref.tidal_parameters().items():
        lines.append(f"| `{name}` | ${sp.latex(expression, mul_symbol='dot')}$ |")
    lines += ["", "| Phase term | Component-mass expression |", "| --- | --- |"]
    for name, expression in ref.tidal_corrections().items():
        lines.append(f"| `{name}` | ${sp.latex(expression, mul_symbol='dot')}$ |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd(), help="DiffGW repository root")
    parser.add_argument("--check", action="store_true", help="Fail if maintained artifacts differ")
    args = parser.parse_args()
    files = {
        "docs/math/taylorf2-tidal-coefficients.md": coefficient_table(),
        "tests/data/taylorf2_tidal_reference_v1.json": json.dumps(fixtures(), indent=2) + "\n",
    }
    for relative, content in files.items():
        path = args.root / relative
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"Reference artifact needs regeneration: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        print(f"{'Checked' if args.check else 'Wrote'} {relative}")


if __name__ == "__main__":
    main()
